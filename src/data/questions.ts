export const questions: Question[] = scenes.map(
  ([focus, category, second, third, text, ...answers], index) => {
    const patterns = [
      [2, 1, -1],
      [1, 0.5, -0.5],
      [-1, -0.5, 0.5],
      [-2, -1, 1],
    ];
    return {
      id: `q${String(index + 1).padStart(2, '0')}`,
      focus,
      category,
      text,
      options: answers.map((text, i) => ({
        id: String.fromCharCode(97 + i),
        text,
        weights: { [focus]: patterns[i][0], [second]: patterns[i][1], [third]: patterns[i][2] },
      })),
    };
  },
);
export const questionById = Object.fromEntries(questions.map((q) => [q.id, q]));
